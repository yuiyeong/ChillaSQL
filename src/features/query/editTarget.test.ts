import { expect, test } from "vitest";
import type {
  EditColumn,
  EditTable,
  RelationKind,
  ResultColumn,
} from "../../shared/api/types";
import { editTargetOf, notEditableText } from "./editTarget";

function editColumn(
  number: number,
  name: string,
  options: Partial<EditColumn> = {},
): EditColumn {
  return {
    number,
    name,
    quotedName: name,
    primaryKey: false,
    updatable: true,
    ...options,
  };
}

function editTable(
  oid: number,
  name: string,
  columns: EditColumn[],
  kind: RelationKind = "table",
): EditTable {
  return { oid, qualifiedName: `public.${name}`, name, kind, columns };
}

function resultColumn(
  name: string,
  tableOid: number,
  columnNumber: number,
): ResultColumn {
  return { name, typeOid: 25, typeModifier: -1, tableOid, columnNumber };
}

const USERS = 100;
const ORDERS = 200;

/** id(1, PK, GENERATED ALWAYS), email(2), 지운 컬럼(3), display_name(4), doubled(5, generated) */
const users = editTable(USERS, "users", [
  editColumn(1, "id", { primaryKey: true, updatable: false }),
  editColumn(2, "email"),
  editColumn(4, "display_name"),
  editColumn(5, "doubled", { updatable: false }),
]);
const orders = editTable(ORDERS, "orders", [
  editColumn(1, "id", { primaryKey: true }),
  editColumn(2, "user_id"),
]);

const usersStar = [
  resultColumn("id", USERS, 1),
  resultColumn("email", USERS, 2),
  resultColumn("display_name", USERS, 4),
  resultColumn("doubled", USERS, 5),
];

function target(
  columns: ResultColumn[],
  tables: EditTable[] | undefined,
  readOnly = false,
  running = false,
) {
  return editTargetOf(columns, tables, readOnly, running);
}

test("single_table_with_primary_key_is_editable", () => {
  const result = target(usersStar, [users]);
  expect(result).not.toBeNull();
  expect(result).toHaveProperty("table", users);
  expect(result).toHaveProperty("keyColumns", [
    { column: users.columns[0], index: 0 },
  ]);
  expect(result).toHaveProperty("columns");
  const columns = (result as { columns: unknown[] }).columns;
  expect(columns[1]).toEqual({ column: users.columns[1] });
  expect(columns[2]).toEqual({ column: users.columns[2] });
});

test("alias_and_duplicate_columns_map_to_one_attnum", () => {
  const result = target(
    [
      resultColumn("id", USERS, 1),
      resultColumn("e", USERS, 2),
      resultColumn("email", USERS, 2),
    ],
    [users],
  );
  expect(result).toHaveProperty("columns", [
    { reason: "generated", name: "id" },
    { column: users.columns[1] },
    { column: users.columns[1] },
  ]);
});

test("the key is read from the first result column with that attnum", () => {
  const result = target(
    [
      resultColumn("email", USERS, 2),
      resultColumn("pk", USERS, 1),
      resultColumn("id", USERS, 1),
    ],
    [users],
  );
  expect(result).toHaveProperty("keyColumns", [
    { column: users.columns[0], index: 1 },
  ]);
});

test("computed_and_generated_columns_are_not_editable", () => {
  const result = target(
    [
      resultColumn("id", USERS, 1),
      resultColumn("upper", 0, 0),
      resultColumn("doubled", USERS, 5),
      resultColumn("email", USERS, 2),
    ],
    [users],
  );
  expect(result).toHaveProperty("columns", [
    { reason: "generated", name: "id" },
    { reason: "computed", name: "upper" },
    { reason: "generated", name: "doubled" },
    { column: users.columns[1] },
  ]);
  expect(notEditableText({ reason: "computed", name: "upper" })).toBe(
    "Not editable: upper is computed.",
  );
  expect(notEditableText({ reason: "generated", name: "doubled" })).toBe(
    "Not editable: doubled is generated by the database.",
  );
});

test("join_names_both_tables", () => {
  const result = target(
    [
      resultColumn("id", ORDERS, 1),
      resultColumn("email", USERS, 2),
      resultColumn("id", USERS, 1),
    ],
    [users, orders],
  );
  expect(result).toEqual({ reason: "manyTables", names: ["orders", "users"] });
  expect(
    notEditableText(result as { reason: "manyTables"; names: string[] }),
  ).toBe("Not editable: rows come from 2 tables (orders, users).");
});

test("many_tables_names_skip_unknown_oids", () => {
  const result = target(
    [
      resultColumn("a", 999, 1),
      resultColumn("b", USERS, 2),
      resultColumn("c", ORDERS, 1),
    ],
    [orders, users],
  );
  expect(result).toEqual({ reason: "manyTables", names: ["users", "orders"] });
});

test("more_than_three_tables_are_cut", () => {
  const extra = [300, 400].map((oid) =>
    editTable(oid, `t${oid}`, [editColumn(1, "id", { primaryKey: true })]),
  );
  const result = target(
    [USERS, ORDERS, 300, 400].map((oid) => resultColumn("id", oid, 1)),
    [users, orders, ...extra],
  );
  expect(result).toEqual({
    reason: "manyTables",
    names: ["users", "orders", "t300", "t400"],
  });
  expect(
    notEditableText(result as { reason: "manyTables"; names: string[] }),
  ).toBe("Not editable: rows come from 4 tables (users, orders, t300, …).");
});

test("view_is_not_a_table", () => {
  const view = editTable(USERS, "active_users", users.columns, "view");
  expect(target(usersStar, [view])).toEqual({
    reason: "notTable",
    name: "active_users",
  });
  expect(notEditableText({ reason: "notTable", name: "active_users" })).toBe(
    "Not editable: active_users is not a table.",
  );
});

test("partitioned_table_is_editable", () => {
  const parted = editTable(USERS, "users", users.columns, "partitioned_table");
  expect(target(usersStar, [parted])).toHaveProperty("table", parted);
});

test("table_without_primary_key", () => {
  const bare = editTable(USERS, "events", [editColumn(1, "payload")]);
  const result = target([resultColumn("payload", USERS, 1)], [bare]);
  expect(result).toEqual({ reason: "noPrimaryKey", name: "events" });
  expect(notEditableText({ reason: "noPrimaryKey", name: "events" })).toBe(
    "Not editable: events has no primary key.",
  );
});

test("missing_primary_key_column", () => {
  const result = target([resultColumn("email", USERS, 2)], [users]);
  expect(result).toEqual({ reason: "primaryKeyMissing", columns: ["id"] });
  expect(
    notEditableText({ reason: "primaryKeyMissing", columns: ["id"] }),
  ).toBe("Not editable: the result does not include the primary key (id).");
});

test("composite_key_needs_both", () => {
  const link = editTable(ORDERS, "links", [
    editColumn(1, "a", { primaryKey: true }),
    editColumn(2, "b", { primaryKey: true }),
    editColumn(3, "note"),
  ]);
  const onlyA = target(
    [resultColumn("a", ORDERS, 1), resultColumn("note", ORDERS, 3)],
    [link],
  );
  expect(onlyA).toEqual({ reason: "primaryKeyMissing", columns: ["b"] });
  expect(
    notEditableText({ reason: "primaryKeyMissing", columns: ["a", "b"] }),
  ).toBe("Not editable: the result does not include the primary key (a, b).");

  const both = target(
    [
      resultColumn("note", ORDERS, 3),
      resultColumn("b", ORDERS, 2),
      resultColumn("a", ORDERS, 1),
    ],
    [link],
  );
  expect(both).toHaveProperty("keyColumns", [
    { column: link.columns[0], index: 2 },
    { column: link.columns[1], index: 1 },
  ]);
});

test("union_has_no_table", () => {
  const result = target(
    [resultColumn("email", 0, 0), resultColumn("count", 0, 0)],
    [],
  );
  expect(result).toEqual({ reason: "noTable" });
  expect(notEditableText({ reason: "noTable" })).toBe(
    "Not editable: no column comes from a table.",
  );
});

test("read_only_wins", () => {
  expect(target([resultColumn("x", 0, 0)], [], true, true)).toEqual({
    reason: "readOnly",
  });
  expect(target(usersStar, undefined, true)).toEqual({ reason: "readOnly" });
  expect(notEditableText({ reason: "readOnly" })).toBe(
    "Not editable: the connection is read-only.",
  );
});

test("running_is_not_editable", () => {
  expect(target(usersStar, [users], false, true)).toEqual({
    reason: "running",
  });
  expect(notEditableText({ reason: "running" })).toBe(
    "Not editable while rows are still coming. Cancel keeps the rows received so far.",
  );
});

test("unknown_tables_wait", () => {
  expect(target(usersStar, undefined)).toBeNull();
});

test("vanished_table_is_gone", () => {
  expect(target(usersStar, [])).toEqual({ reason: "gone" });
  expect(target(usersStar, [orders])).toEqual({ reason: "gone" });
  expect(notEditableText({ reason: "gone" })).toBe(
    "Not editable: the table no longer exists.",
  );
});
